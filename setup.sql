CREATE TABLE CLIENTE (
	IDCLIENTE INT PRIMARY KEY AUTO_INCREMENT,
	NOME VARCHAR(30) NOT NULL,
	SOBRENOME VARCHAR(30) NOT NULL,
	EMAIL VARCHAR(60) NOT NULL,
	SEXO CHAR(1) NOT NULL,
	NASCIMENTO DATE NOT NULL
	) ENGINE=InnoDB DEFAULT CHARSET=utf8;

CREATE TABLE LOG_CLIENTE(
	ID INT PRIMARY KEY AUTO_INCREMENT,
	IDCLIENTE INT,
	OPERACAO VARCHAR(10),
	DATA_OPERACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
	) ENGINE=InnoDB DEFAULT CHARSET=utf8;

delimiter |
CREATE TRIGGER AFTER_CLIENTE_INSERT
AFTER INSERT
ON CLIENTE FOR EACH ROW 
BEGIN 
	INSERT INTO LOG_CLIENTE (IDCLIENTE,OPERACAO) VALUES (NEW.IDCLIENTE,'Inclusão');
END;
|
delimiter |
CREATE TRIGGER AFTER_CLIENTE_UPDATE
AFTER UPDATE
ON CLIENTE FOR EACH ROW 
BEGIN 
	INSERT INTO LOG_CLIENTE (IDCLIENTE,OPERACAO) VALUES (NEW.IDCLIENTE,'Alteração');
END;
|
delimiter |
CREATE TRIGGER AFTER_CLIENTE_DELETE
AFTER DELETE
ON CLIENTE FOR EACH ROW 
BEGIN 
	INSERT INTO LOG_CLIENTE (IDCLIENTE,OPERACAO) VALUES (OLD.IDCLIENTE,'Exclusão');
END;
|
delimiter ;

